// Builds TitaniumSim.html: the whole sim (code, three.js, Rapier, routine.cpp) in one file that opens by
// double-click with no server and no internet. Browsers block module files on file://, so everything is inlined.
//   npm install && npm run build
import { build } from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => path.join(root, p);

// Same mapping as the import map in index.html.
const vendor = {
	name: 'vendor',
	setup(b) {
		b.onResolve({ filter: /^three$/ }, () => ({ path: rel('vendor/three/three.module.min.js') }));
		b.onResolve({ filter: /^three\/addons\// }, (a) => ({ path: rel('vendor/three/addons/' + a.path.slice('three/addons/'.length)) }));
		b.onResolve({ filter: /^@dimforge\/rapier3d-compat$/ }, () => ({ path: rel('vendor/rapier/rapier.es.js') }));
	},
};

const out = await build({
	entryPoints: [rel('js/main.js')], bundle: true, format: 'esm', target: 'es2022',
	minify: true, legalComments: 'eof', write: false, plugins: [vendor], logLevel: 'warning',
});
// Inside <script>, "</script" ends the tag and "<!--" changes how it's parsed; both only appear in strings here.
const code = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

let html = fs.readFileSync(rel('index.html'), 'utf8');
const icon = 'data:image/png;base64,' + fs.readFileSync(rel('icons/icon-192.png')).toString('base64');
const routine = fs.readFileSync(rel('routine.cpp'), 'utf8');
const swap = (from, to) => { if (!from.test(html)) throw new Error('index.html changed: no match for ' + from); html = html.replace(from, to); };
swap(/<!-- app:begin[\s\S]*?<!-- app:end -->/, `<link rel="icon" href="${icon}" type="image/png">`);
swap(/<!-- Libraries are in vendor\/[^]*?<\/script>/, '');
swap(/<div class="hint" id="appHint">[\s\S]*?<\/div>/, '<div class="hint" id="appHint">Offline single-file version. Copy this one file anywhere and double-click it.</div>');
swap(/<script type="module" src="js\/main.js"><\/script>/, () =>
	`<script>window.ROUTINE_CPP = ${JSON.stringify(routine).replace(/<\//g, '<\\/')};</script>\n<script type="module">\n${code}</script>`);
html = html.replace('<head>', '<head>\n<!-- Generated by tools/build-offline.mjs from index.html. Edit the source files, not this. -->');

fs.writeFileSync(rel('TitaniumSim.html'), html);
console.log(`TitaniumSim.html ${(html.length / 1e6).toFixed(1)} MB`);
